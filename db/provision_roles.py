"""Provision the ai_hub_owner / ai_hub_app roles on the Azure PG flexible server.

Connects as the Entra admin (AAD access token fetched via az CLI), then:
  1. Creates login roles `ai_hub_owner` (DDL: Alembic + data migration) and
     `ai_hub_app` (runtime DML) with generated passwords — skipped if they exist.
  2. Grants CONNECT + schema privileges on the main and test databases.
  3. Creates the test database "ai-enablement-hub-test" if missing.
  4. As ai_hub_owner, sets DEFAULT PRIVILEGES so every future table/sequence the
     owner creates (i.e. every Alembic migration) is automatically DML-accessible
     to ai_hub_app — the permanent fix for the "new tables lack grants" pain.
  5. Runs a probe: owner creates a table, app reads it with no explicit grant.

Credentials are written to db/.env (git-ignored). Idempotent: safe to re-run;
existing roles/databases are left alone (use --rotate-passwords to reset).

Usage:
    uv run provision_roles.py [--rotate-passwords]
"""

from __future__ import annotations

import argparse
import secrets
import subprocess
import sys
from pathlib import Path

import psycopg
from psycopg import sql

HOST = "imaginemore-playground-pg.postgres.database.azure.com"
ADMIN_USER = "danneelm@delawareconsulting.com"
MAIN_DB = "ai-enablement-hub"
TEST_DB = "ai-enablement-hub-test"
OWNER_ROLE = "ai_hub_owner"
APP_ROLE = "ai_hub_app"
ENV_FILE = Path(__file__).parent / ".env"

AZ = r"C:\Program Files\Microsoft SDKs\Azure\CLI2\wbin\az.cmd"


def aad_token() -> str:
    out = subprocess.run(
        [AZ, "account", "get-access-token",
         "--resource", "https://ossrdbms-aad.database.windows.net",
         "--query", "accessToken", "-o", "tsv"],
        capture_output=True, text=True, check=True,
    )
    return out.stdout.strip()


def connect(user: str, password: str, dbname: str) -> psycopg.Connection:
    return psycopg.connect(
        host=HOST, port=5432, dbname=dbname, user=user, password=password,
        sslmode="require", autocommit=True,
    )


def read_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                values[k.strip()] = v.strip()
    return values


def write_env(values: dict[str, str]) -> None:
    lines = ["# Azure PG credentials — generated by provision_roles.py. DO NOT COMMIT."]
    lines += [f"{k}={v}" for k, v in sorted(values.items())]
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    gitignore = Path(__file__).parent / ".gitignore"
    entries = set()
    if gitignore.exists():
        entries = set(gitignore.read_text(encoding="utf-8").split())
    if ".env" not in entries:
        with gitignore.open("a", encoding="utf-8") as f:
            f.write(".env\n")


def role_exists(cur: psycopg.Cursor, role: str) -> bool:
    cur.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (role,))
    return cur.fetchone() is not None


def db_exists(cur: psycopg.Cursor, name: str) -> bool:
    cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (name,))
    return cur.fetchone() is not None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rotate-passwords", action="store_true")
    args = parser.parse_args()

    env = read_env()
    token = aad_token()
    print(f"Connected as Entra admin {ADMIN_USER}")

    with connect(ADMIN_USER, token, MAIN_DB) as admin:
        cur = admin.cursor()

        # 1. Roles
        for role, env_key in ((OWNER_ROLE, "AZURE_PG_OWNER_PASSWORD"),
                              (APP_ROLE, "AZURE_PG_APP_PASSWORD")):
            exists = role_exists(cur, role)
            if exists and not args.rotate_passwords:
                if env_key not in env:
                    sys.exit(f"Role {role} exists but {env_key} missing from db/.env — "
                             f"re-run with --rotate-passwords to reset it.")
                print(f"role {role}: exists, keeping password")
                continue
            pw = secrets.token_urlsafe(24)
            verb = "ALTER" if exists else "CREATE"
            cur.execute(
                sql.SQL("{} ROLE {} WITH LOGIN PASSWORD {}").format(
                    sql.SQL(verb), sql.Identifier(role), sql.Literal(pw)
                )
            )
            print(f"role {role}: {'password rotated' if exists else 'created'}")
            env[env_key] = pw

        # 2. Database-level + schema-level grants on the main DB
        cur.execute(f'GRANT CONNECT, TEMPORARY ON DATABASE "{MAIN_DB}" TO {OWNER_ROLE}, {APP_ROLE}')
        cur.execute(f"GRANT ALL ON SCHEMA public TO {OWNER_ROLE}")
        cur.execute(f"GRANT USAGE ON SCHEMA public TO {APP_ROLE}")
        cur.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO {APP_ROLE}")
        cur.execute(f"GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO {APP_ROLE}")
        print(f"grants applied on {MAIN_DB}")

        # 3. Test database
        if not db_exists(cur, TEST_DB):
            try:
                cur.execute(f"GRANT {OWNER_ROLE} TO CURRENT_USER")
                cur.execute(f'CREATE DATABASE "{TEST_DB}" OWNER {OWNER_ROLE}')
                print(f"database {TEST_DB}: created (owner {OWNER_ROLE})")
            except psycopg.Error as e:
                print(f"owner-create failed ({e}); creating without owner")
                cur.execute(f'CREATE DATABASE "{TEST_DB}"')
                print(f"database {TEST_DB}: created")
        else:
            print(f"database {TEST_DB}: exists")
        cur.execute(f'GRANT CONNECT, TEMPORARY ON DATABASE "{TEST_DB}" TO {OWNER_ROLE}, {APP_ROLE}')

    # schema grants inside the test DB (its own `public` schema)
    with connect(ADMIN_USER, token, TEST_DB) as admin_test:
        cur = admin_test.cursor()
        cur.execute(f"GRANT ALL ON SCHEMA public TO {OWNER_ROLE}")
        cur.execute(f"GRANT USAGE ON SCHEMA public TO {APP_ROLE}")
        print(f"grants applied on {TEST_DB}")

    # 4. Default privileges — run AS ai_hub_owner in each DB, so everything the
    #    owner creates in future (Alembic migrations) is app-accessible.
    owner_pw = env["AZURE_PG_OWNER_PASSWORD"]
    for dbname in (MAIN_DB, TEST_DB):
        with connect(OWNER_ROLE, owner_pw, dbname) as owner:
            cur = owner.cursor()
            cur.execute(f"ALTER DEFAULT PRIVILEGES IN SCHEMA public "
                        f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {APP_ROLE}")
            cur.execute(f"ALTER DEFAULT PRIVILEGES IN SCHEMA public "
                        f"GRANT USAGE, SELECT ON SEQUENCES TO {APP_ROLE}")
            print(f"default privileges set by {OWNER_ROLE} on {dbname}")

    # 5. Probe: owner creates, app reads with no explicit grant
    app_pw = env["AZURE_PG_APP_PASSWORD"]
    with connect(OWNER_ROLE, owner_pw, MAIN_DB) as owner:
        owner.cursor().execute("CREATE TABLE IF NOT EXISTS _grant_probe (id int)")
    try:
        with connect(APP_ROLE, app_pw, MAIN_DB) as app:
            cur = app.cursor()
            cur.execute("INSERT INTO _grant_probe VALUES (1)")
            cur.execute("SELECT count(*) FROM _grant_probe")
            n = cur.fetchone()[0]
        print(f"PROBE OK: {APP_ROLE} inserted+selected _grant_probe without explicit grant (rows={n})")
    finally:
        with connect(OWNER_ROLE, owner_pw, MAIN_DB) as owner:
            owner.cursor().execute("DROP TABLE IF EXISTS _grant_probe")

    env.setdefault("AZURE_PG_HOST", HOST)
    env["AZURE_PG_OWNER_DSN"] = (
        f"postgresql://{OWNER_ROLE}:{env['AZURE_PG_OWNER_PASSWORD']}@{HOST}:5432/{MAIN_DB}?sslmode=require"
    )
    env["AZURE_PG_APP_DSN"] = (
        f"postgresql://{APP_ROLE}:{env['AZURE_PG_APP_PASSWORD']}@{HOST}:5432/{MAIN_DB}?sslmode=require"
    )
    write_env(env)
    print(f"\nCredentials + DSNs written to {ENV_FILE} (git-ignored). Provisioning complete.")


if __name__ == "__main__":
    main()
